#!/usr/bin/env python3
"""Port the reviewed exact-expression host probe to the existing native test target.

This uses production source extraction, not a separately maintained area-basis implementation.
Re-run after any change to the projection; the source manifest binds the extracted snapshot.
"""
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[1]
module = runpy.run_path(str(ROOT / 'scripts/tests/test_spray_product_recursion.py'))
projection = module['properties'](module['VIEW'].read_text())['guidedProductLines']
fragment = projection[projection.index('let newSpray ='):projection.index('// THE label rate')]
source = module['host_source'](fragment)
for name in ['OperationType', 'ChemicalRateBasis', 'SprayProductRateBasis', 'Record', 'Line', 'Product', 'Inputs', 'Flow', 'Probe']:
    source = re.sub(r'\b' + name + r'\b', 'Build189' + name, source)
declarations, body = source.split('let probe = Build189Probe()', 1)
declarations = declarations.replace('import Foundation', 'import Foundation\nimport XCTest')
body = 'let probe = Build189Probe()' + body
body = body.replace('precondition(', 'XCTAssertTrue(')
body += '\nXCTAssertEqual(cases, 111)\n'
text = '// Generated by scripts/generate-pr24-native-expression-test.py from production.\n'
text += '// Synthetic model boundaries: not a full SwiftUI or dose-engine test.\n'
text += declarations
text += '\nfinal class SprayProductRecursionExpressionTests: XCTestCase {\n'
text += '    @MainActor func testExactProductionAreaExpressionAcross111Scenarios() {\n'
text += '\n'.join('        ' + line for line in body.splitlines())
text += '\n    }\n}\n'
text = '\n'.join(line.rstrip() for line in text.splitlines()) + '\n'
path = ROOT / 'ios/VineTrackTests/SprayProductRecursionExpressionTests.swift'
path.write_text(text)
print(path.relative_to(ROOT))
